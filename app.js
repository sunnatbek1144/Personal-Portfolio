const $ = s => document.querySelectorAll(s)
function setLang(l) {
	const d = T[l]
	document.documentElement.lang = l
	$('[data-i18n]').forEach(e => (e.textContent = d[e.dataset.i18n]))
	$('[data-i18n-html]').forEach(e => (e.innerHTML = d[e.dataset.i18nHtml]))
	$('.langs button').forEach(b => b.classList.toggle('on', b.dataset.l === l))
	try {
		localStorage.setItem('lang', l)
	} catch (e) {}
}
$('.langs button').forEach(b => (b.onclick = () => setLang(b.dataset.l)))
